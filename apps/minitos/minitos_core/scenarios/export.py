"""Export the integration events of a freshly seeded scenario (TCL-006).

terminal-oes keeps a copy of these events as a test fixture
(``apps/terminal-oes/execution/fixtures/scenario_import_v1_events.json``) so
its reset/ingest tests use the exact payloads MiniTOS publishes. The MiniTOS
test suite fails when the seed changes without refreshing that copy.
"""

from ..models import IntegrationOutbox, SiteConfigurationSnapshot
from ..serializers import SiteConfigurationSnapshotSerializer
from . import reset_scenario, run_step

FIXTURE_SCHEMAS = (
    'scms.site.created.v1',
    'scms.site.configuration.published.v1',
    'scms.order.released.v1',
)


def scenario_events(name='import_v1'):
    """Reset ``name``, release the first discharge order and return the events."""
    reset_scenario(name)
    run_step(name, 'release-discharge')
    events = {}
    for event in IntegrationOutbox.objects.filter(schema__in=FIXTURE_SCHEMAS).order_by('created_at'):
        events[event.schema] = {'topic': event.topic, 'payload': event.payload}
    snapshot = SiteConfigurationSnapshot.objects.get()
    data = dict(SiteConfigurationSnapshotSerializer(snapshot).data)
    data.pop('created_at', None)
    data['site'] = str(data['site'])
    return {
        '_comment': (
            'Generated by MiniTOS minitos_core.scenarios.export.scenario_events("import_v1") '
            '(TCL-006). Regenerate with: python manage.py scenario_export_events '
            '--settings=minitos_site.settings_test > '
            '../terminal-oes/execution/fixtures/scenario_import_v1_events.json'
        ),
        'events': events,
        'snapshot_document': data,
    }
